// Builds the translated public pages from the English pages:
//   French (Sprint 7): /fr, /fr/estimate, /fr/policies, /fr/terms, /fr/privacy  ← tools/i18n/fr-pages.json
//   Arabic (Sprint 8): /ar, /ar/estimate, …  (dir="rtl", Arabic font, assets/rtl.css) ← tools/i18n/ar-pages.json
//
//   node tools/build-i18n.mjs           writes fr/… and ar/…
//   node tools/build-i18n.mjs --check   fails if a page is out of date or an English text has no translation
//
// After ANY change to an English public page, run it again and commit everything. The English page stays the
// source: structure, scripts and styles are copied, only the texts and the links change. Each json file has
// "common" + one section per page. A text is replaced only when it is a whole piece of text (between two tags,
// or a whole string in quotes). Translations must not contain ASCII quotes: write ’ and « » instead.
// The client account is translated in the browser instead (assets/i18n.js + assets/i18n/<lang>.json).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://www.ddpsourcing.com";
export const LANGS = ["fr", "ar"];
export const PAGES = [
  { src: "index.html", path: "" },
  { src: "estimate/index.html", path: "/estimate", out: "estimate/index.html" },
  { src: "policies.html", path: "/policies" },
  { src: "terms.html", path: "/terms" },
  { src: "privacy.html", path: "/privacy" },
];
const outFile = (page, lang) => lang + "/" + (page.out || page.src);
const enUrl = (page) => page.path || "/";
const NAMES = { en: ["EN", "English version"], fr: ["FR", "Version française"], ar: ["ع", "النسخة العربية"] };
const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export function loadDict(lang) {
  return { pages: JSON.parse(read(`tools/i18n/${lang}-pages.json`)) };
}

// Replaces whole pieces of text. Returns the new html and the keys that were not found.
export function translate(html, pairs, required) {
  const missing = [];
  const keys = Object.keys(pairs).filter((k) => !k.startsWith("_")).sort((a, b) => b.length - a.length);
  for (const en of keys) {
    const fr = pairs[en];
    if (/['"]/.test(fr)) throw new Error(`ASCII quote in the translation of "${en}": use ’ or « »`);
    const body = esc(en.trim()).replace(/\s+/g, "\\s+");
    const re = new RegExp(`(?<=[>"'\`]\\s*)${body}(?=\\s*[<"'\`])`, "g");
    let n = 0;
    html = html.replace(re, () => { n++; return fr; });
    if (!n && required) missing.push(en);
  }
  return { html, missing };
}

// Public links go to the pages of the same language; assets, the API, the CRM and anchors stay as they are.
export function rewriteLinks(html, lang) {
  return html
    .replace(/(["'(])\/(account|estimate|policies|terms|privacy)(?=[?#"'\/)\s]|$)/g, `$1/${lang}/$2`)
    .replace(/href="\/(#[^"]*)?"/g, (m, hash) => `href="/${lang}${hash || ""}"`);
}

export function build(page, lang, dict) {
  let html = read(page.src);
  const own = dict.pages[page.src] || {};
  const pairs = { ...dict.pages.common, ...own };
  const r = translate(html, own, true);
  html = translate(r.html, pairs, false).html;
  html = rewriteLinks(html, lang);
  html = html.replace(/<html lang="en"/, lang === "ar" ? '<html lang="ar" dir="rtl"' : `<html lang="${lang}"`);
  // The switch to this language becomes the switch back to English.
  html = html.replace(new RegExp(`<a([^>]*)data-lang-switch="${lang}"([^>]*)>[^<]*<\\/a>`, "g"), (m) =>
    m.replace(/href="[^"]*"/, `href="${enUrl(page)}"`).replace(/hreflang="\w+"/, 'hreflang="en"').replace(/ lang="\w+"/, ' lang="en"')
      .replace(/aria-label="[^"]*"/, `aria-label="${NAMES.en[1]}"`).replace(/>[^<]*<\/a>$/, `>${NAMES.en[0]}</a>`)
      .replace(/data-lang-switch="\w+"/, 'data-lang-switch="en"'));
  html = html.replace(/<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${SITE}/${lang}${page.path}">`);
  if (lang === "ar") {
    // Arabic font (Google Fonts, already allowed by the CSP) and the right-to-left fixes.
    html = html.replace("</head>", '<link href="https://fonts.googleapis.com/css2?family=Tajawal:wght@400;500;700;800&display=swap" rel="stylesheet">\n<link rel="stylesheet" href="/assets/rtl.css">\n</head>');
  }
  const banner = `<!-- Generated by tools/build-i18n.mjs from ${page.src}. Do not edit: change the English page or tools/i18n/${lang}-pages.json, then run the script. -->\n`;
  html = html.replace(/^<!doctype html>\n?/i, (m) => m + banner);
  return { html, missing: r.missing };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const check = process.argv.includes("--check");
  let bad = 0;
  for (const lang of LANGS) {
    const dict = loadDict(lang);
    for (const page of PAGES) {
      const { html, missing } = build(page, lang, dict);
      if (missing.length) { bad++; console.log(`${lang} ${page.src}: ${missing.length} English text(s) not found:\n  - ` + missing.join("\n  - ")); }
      const out = path.join(ROOT, outFile(page, lang));
      if (check) {
        const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
        if (cur !== html) { bad++; console.log(`${outFile(page, lang)} is out of date: run node tools/build-i18n.mjs`); }
      } else {
        fs.mkdirSync(path.dirname(out), { recursive: true });
        fs.writeFileSync(out, html);
        console.log("wrote " + outFile(page, lang));
      }
    }
  }
  process.exit(bad ? 1 : 0);
}
