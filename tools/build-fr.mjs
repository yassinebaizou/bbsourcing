// Builds the French public pages (Sprint 7) from the English pages and the translations in
// tools/i18n/fr-pages.json ("common" + one section per page). The client account is translated in the
// browser instead (assets/i18n.js + assets/i18n/fr.json).
//
//   node tools/build-fr.mjs           writes fr/index.html, fr/estimate/index.html, fr/policies.html, fr/terms.html, fr/privacy.html
//   node tools/build-fr.mjs --check   fails if a French page is out of date or an English text has no translation
//
// After ANY change to an English public page, run it again and commit both. The English page stays the
// source: structure, scripts and styles are copied, only the texts and the links change.
// Rules for translations: a text is replaced only when it is a whole piece of text (between two tags, or a
// whole string in quotes). French texts must not contain ASCII quotes: write ’ and « » instead.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SITE = "https://www.ddpsourcing.com";
export const PAGES = [
  { src: "index.html", out: "fr/index.html", en: "/", fr: "/fr" },
  { src: "estimate/index.html", out: "fr/estimate/index.html", en: "/estimate", fr: "/fr/estimate" },
  { src: "policies.html", out: "fr/policies.html", en: "/policies", fr: "/fr/policies" },
  { src: "terms.html", out: "fr/terms.html", en: "/terms", fr: "/fr/terms" },
  { src: "privacy.html", out: "fr/privacy.html", en: "/privacy", fr: "/fr/privacy" },
];
const read = (f) => fs.readFileSync(path.join(ROOT, f), "utf8");
const esc = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export function loadDict() {
  return { pages: JSON.parse(read("tools/i18n/fr-pages.json")) };
}

// Replaces whole pieces of text. Returns the new html and the keys that were not found.
export function translate(html, pairs, required) {
  const missing = [];
  const keys = Object.keys(pairs).filter((k) => !k.startsWith("_")).sort((a, b) => b.length - a.length);
  for (const en of keys) {
    const fr = pairs[en];
    if (/['"]/.test(fr)) throw new Error(`ASCII quote in the French text of "${en}": use ’ or « »`);
    const body = esc(en.trim()).replace(/\s+/g, "\\s+");
    const re = new RegExp(`(?<=[>"'\`]\\s*)${body}(?=\\s*[<"'\`])`, "g");
    let n = 0;
    html = html.replace(re, () => { n++; return fr; });
    if (!n && required) missing.push(en);
  }
  return { html, missing };
}

// Public links go to the French pages; assets, the API, the CRM and anchors stay as they are.
export function rewriteLinks(html) {
  return html
    .replace(/(["'(])\/(account|estimate|policies|terms|privacy)(?=[?#"'\/)\s]|$)/g, "$1/fr/$2")
    .replace(/href="\/(#[^"]*)?"/g, (m, hash) => `href="/fr${hash || ""}"`);
}

export function build(page, dict) {
  let html = read(page.src);
  const pairs = { ...dict.pages.common, ...(dict.pages[page.src] || {}) };
  const own = dict.pages[page.src] || {};
  let r = translate(html, own, true);
  html = r.html;
  const missing = r.missing;
  html = translate(html, pairs, false).html;
  html = rewriteLinks(html);
  html = html.replace(/<html lang="en"/, '<html lang="fr"');
  // The switcher points back to the English page.
  html = html.replace(/<a([^>]*)data-lang-switch([^>]*)>[^<]*<\/a>/g, (m) =>
    m.replace(/href="[^"]*"/, `href="${page.en}"`).replace(/hreflang="fr"/, 'hreflang="en"').replace(/lang="fr"/, 'lang="en"')
      .replace(/aria-label="[^"]*"/, 'aria-label="English version"').replace(/>[^<]*<\/a>$/, ">EN</a>")
      .replace(/data-lang-switch(="[^"]*")?/, 'data-lang-switch="en"'));
  html = html.replace(/<link rel="canonical" href="[^"]*">/, `<link rel="canonical" href="${SITE}${page.fr}">`);
  const banner = `<!-- Generated by tools/build-fr.mjs from ${page.src}. Do not edit: change the English page or tools/i18n/fr-pages.json, then run the script. -->\n`;
  html = html.replace(/^<!doctype html>\n?/i, (m) => m + banner);
  return { html, missing };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const check = process.argv.includes("--check");
  const dict = loadDict();
  let bad = 0;
  for (const page of PAGES) {
    const { html, missing } = build(page, dict);
    if (missing.length) { bad++; console.log(`${page.src}: ${missing.length} English text(s) not found:\n  - ` + missing.join("\n  - ")); }
    const out = path.join(ROOT, page.out);
    if (check) {
      const cur = fs.existsSync(out) ? fs.readFileSync(out, "utf8") : "";
      if (cur !== html) { bad++; console.log(`${page.out} is out of date: run node tools/build-fr.mjs`); }
    } else {
      fs.mkdirSync(path.dirname(out), { recursive: true });
      fs.writeFileSync(out, html);
      console.log("wrote " + page.out);
    }
  }
  process.exit(bad ? 1 : 0);
}
